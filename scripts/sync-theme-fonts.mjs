#!/usr/bin/env node
/**
 * sync-theme-fonts.mjs — ships the web fonts of the library themes (self-hosted, no Google CDN).
 *
 * Source: Fontsource packages (devDependencies, OFL-1.1). For every family in FONTS the script
 *   1. copies the woff2 files of the latin + latin-ext subsets and the licence to themes/fonts/<id>/
 *   2. writes an @font-face block (font-family = the name the themes use) into every theme that uses
 *      the family, between the markers `/* @fonts:start *\/` … `/* @fonts:end *\/`
 * Themes reference the files as /_assets/fonts/<id>/<file>; src/theme/copy.js copies exactly the
 * referenced files into the build output.
 *
 * Usage: node scripts/sync-theme-fonts.mjs [--themes <dir>]... [--check]
 *   --themes  additional theme folder to update (e.g. the cms-theme sources); site/themes always
 *   --check   no writes; exit 1 if a theme is out of date or a referenced font file is missing
 */
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const FONTS_DIR = path.join(ROOT, 'themes', 'fonts');
const SUBSETS = ['latin', 'latin-ext'];
const START = '/* @fonts:start — generated by scripts/sync-theme-fonts.mjs, do not edit */';
const END = '/* @fonts:end */';

// family (as written in the themes) → Fontsource package; italic only where a theme uses it
export const FONTS = {
  'Cormorant Garamond': { pkg: '@fontsource-variable/cormorant-garamond', italic: true },
  'DM Sans': { pkg: '@fontsource-variable/dm-sans' },
  'EB Garamond': { pkg: '@fontsource-variable/eb-garamond', italic: true },
  'IBM Plex Mono': { pkg: '@fontsource/ibm-plex-mono', weights: [400, 500] },
  'IBM Plex Sans': { pkg: '@fontsource-variable/ibm-plex-sans' },
  Inter: { pkg: '@fontsource-variable/inter' },
  'JetBrains Mono': { pkg: '@fontsource-variable/jetbrains-mono' },
  Jost: { pkg: '@fontsource-variable/jost' },
  Lato: { pkg: '@fontsource/lato', weights: [300, 400, 700] },
  'Libre Baskerville': { pkg: '@fontsource-variable/libre-baskerville', italic: true },
  Merriweather: { pkg: '@fontsource-variable/merriweather', italic: true },
  'Nunito Sans': { pkg: '@fontsource-variable/nunito-sans' },
  Oswald: { pkg: '@fontsource-variable/oswald' },
  'Playfair Display': { pkg: '@fontsource-variable/playfair-display', italic: true },
  'Plus Jakarta Sans': { pkg: '@fontsource-variable/plus-jakarta-sans' },
  'Public Sans': { pkg: '@fontsource-variable/public-sans' },
  Raleway: { pkg: '@fontsource-variable/raleway' },
  'Source Sans 3': { pkg: '@fontsource-variable/source-sans-3' },
  'Source Serif 4': { pkg: '@fontsource-variable/source-serif-4', italic: true }
};

const args = process.argv.slice(2);
const check = args.includes('--check');
const themeDirs = [path.join(ROOT, 'themes')];
args.forEach((a, i) => { if (a === '--themes' && args[i + 1]) themeDirs.push(path.resolve(args[i + 1])); });

function packageDir(pkg) {
  return path.dirname(require.resolve(`${pkg}/package.json`));
}

/** @font-face blocks of one Fontsource CSS file: [{ file, subset, style, weight, unicodeRange }] */
function parseFontsourceCss(cssFile) {
  const css = fs.readFileSync(cssFile, 'utf8');
  const faces = [];
  for (const block of css.match(/@font-face\s*{[^}]*}/g) || []) {
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
    if (!file) continue;
    const subset = SUBSETS.slice().reverse().find((s) => file.includes(`-${s}-`)); // latin-ext before latin
    if (!subset || (subset === 'latin' && /-latin-ext-/.test(file))) continue;
    faces.push({
      file,
      subset,
      style: /font-style:\s*(\w+)/.exec(block)[1],
      weight: /font-weight:\s*([\d\s]+);/.exec(block)[1].trim(),
      unicodeRange: /unicode-range:\s*([^;]+);/.exec(block)[1].trim()
    });
  }
  return faces;
}

/** All faces of a family, from the package's CSS entry points. */
function facesFor(family) {
  const spec = FONTS[family];
  const dir = packageDir(spec.pkg);
  const cssFiles = spec.weights
    ? spec.weights.flatMap((w) => [`${w}.css`, ...(spec.italic ? [`${w}-italic.css`] : [])])
    : ['wght.css', ...(spec.italic ? ['wght-italic.css'] : [])];
  const id = path.basename(spec.pkg);
  return {
    id,
    dir,
    faces: cssFiles.flatMap((f) => parseFontsourceCss(path.join(dir, f))).map((face) => ({ ...face, family, id }))
  };
}

function renderFaces(faces) {
  return faces.map((f) => [
    '@font-face {',
    `  font-family: '${f.family}';`,
    `  font-style: ${f.style};`,
    `  font-weight: ${f.weight};`,
    '  font-display: swap;',
    `  src: url('/_assets/fonts/${f.id}/${f.file}') format('woff2');`,
    `  unicode-range: ${f.unicodeRange};`,
    '}'
  ].join('\n')).join('\n');
}

/** Families a theme uses: names in --t-font-* tokens and font-family declarations that we ship. */
export function familiesInTheme(css) {
  const withoutBlock = css.replace(/\/\* @fonts:start[\s\S]*?\/\* @fonts:end \*\//, '');
  const used = new Set();
  const decls = withoutBlock.match(/(?:--t-font-[\w-]+|font-family)\s*:\s*[^;]+;/g) || [];
  for (const decl of decls) {
    const value = decl.slice(decl.indexOf(':') + 1);
    for (const part of value.split(',')) {
      const name = part.replace(/;/g, '').trim().replace(/^['"]|['"]$/g, '');
      if (FONTS[name]) used.add(name);
    }
  }
  return [...used].sort();
}

function insertBlock(css, block) {
  const cleaned = css.replace(/\n*\/\* @fonts:start[\s\S]*?\/\* @fonts:end \*\/\n*/, '\n\n');
  if (!block) return cleaned.replace(/\n{3,}/g, '\n\n');
  // after the leading header comment (if any)
  const header = /^\s*\/\*[\s\S]*?\*\/\n*/.exec(cleaned);
  const at = header ? header[0].length : 0;
  return `${cleaned.slice(0, at).replace(/\n*$/, '\n\n')}${START}\n${block}\n${END}\n\n${cleaned.slice(at).replace(/^\n+/, '')}`;
}

// ─── run ────────────────────────────────────────────────────
const cache = new Map();
const family = (name) => {
  if (!cache.has(name)) cache.set(name, facesFor(name));
  return cache.get(name);
};

let problems = 0;
const usedIds = new Set();
for (const dir of themeDirs) {
  for (const file of fs.readdirSync(dir).filter((f) => /^theme-.*\.css$/.test(f)).sort()) {
    const full = path.join(dir, file);
    const css = fs.readFileSync(full, 'utf8');
    const families = familiesInTheme(css);
    const faces = families.flatMap((name) => family(name).faces);
    families.forEach((name) => usedIds.add(family(name).id));
    const next = insertBlock(css, faces.length ? renderFaces(faces) : '');
    if (next !== css) {
      if (check) { console.error(`veraltet: ${full}`); problems++; }
      else fs.writeFileSync(full, next);
    }
    console.log(`${file.padEnd(24)} ${families.join(', ') || '(keine mitgelieferten Schriften)'}`);
  }
}

if (!check) {
  fs.rmSync(FONTS_DIR, { recursive: true, force: true });
  let bytes = 0;
  for (const name of Object.keys(FONTS)) {
    const { id, dir, faces } = family(name);
    if (!usedIds.has(id)) continue;
    const target = path.join(FONTS_DIR, id);
    fs.mkdirSync(target, { recursive: true });
    for (const face of faces) {
      fs.copyFileSync(path.join(dir, 'files', face.file), path.join(target, face.file));
      bytes += fs.statSync(path.join(target, face.file)).size;
    }
    fs.copyFileSync(path.join(dir, 'LICENSE'), path.join(target, 'LICENSE'));
  }
  console.log(`\n${usedIds.size} Familien, ${(bytes / 1024 / 1024).toFixed(2)} MB woff2 → ${path.relative(ROOT, FONTS_DIR)}/`);
} else {
  for (const dir of themeDirs) {
    for (const file of fs.readdirSync(dir).filter((f) => /^theme-.*\.css$/.test(f))) {
      const css = fs.readFileSync(path.join(dir, file), 'utf8');
      for (const [, rel] of css.matchAll(/url\('\/_assets\/fonts\/([^']+)'\)/g)) {
        if (!fs.existsSync(path.join(FONTS_DIR, rel))) { console.error(`fehlt: themes/fonts/${rel} (${file})`); problems++; }
      }
    }
  }
  process.exit(problems ? 1 : 0);
}
